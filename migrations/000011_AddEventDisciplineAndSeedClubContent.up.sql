ALTER TABLE events ADD COLUMN IF NOT EXISTS discipline TEXT NOT NULL DEFAULT '';

UPDATE events
SET discipline = 'CourtSword'
WHERE discipline = ''
  AND (
    LOWER(title) LIKE '%courtsword%'
    OR LOWER(description) LIKE '%courtsword%'
    OR type = 'training'
  );

